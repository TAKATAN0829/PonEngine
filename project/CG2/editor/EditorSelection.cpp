#include "EditorSelection.h"

//=================================================================================================//
// 選択IDの取得

ModelId EditorSelection::Get() const {
	return selected_;
}

//=================================================================================================//
// モデル選択

void EditorSelection::Select(ModelId id) {
	selected_ = id;
}

//=================================================================================================//
// 選択解除

void EditorSelection::Clear() {
	selected_ = 0;
}
